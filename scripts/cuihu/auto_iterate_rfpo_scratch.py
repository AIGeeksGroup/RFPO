    assert_pure_rfpo(candidate)
    log = root / "logs" / f"{candidate.run}.out"
    pid_file = root / "logs" / f"{candidate.run}.pid"
    overrides = " ".join(
        f"'{arg}'" for arg in (*BASE_OVERRIDES, *candidate.overrides, f"wandb.sweep_name_prefix={candidate.run}")
    )
    cmd = (
        f"export CUIHU_ROOT={root}; "
        f"export CUDA_VISIBLE_DEVICES={candidate.gpu}; "
        "export VIVIDEX_HEADLESS_NO_RENDER=1; "
        "export WANDB_MODE=offline; "
        f"cd {repo}; "
        "source scripts/cuihu/common.sh; "
        f"bash scripts/server/train_state_single.sh '{SEQ}' '{candidate.run}' {overrides}"
    )
    full = f"nohup bash -lc {cmd!r} > {str(log)!r} 2>&1 & echo $! > {str(pid_file)!r}"
    sh(full, cwd=repo)
    time.sleep(20)


