def should_stop_run(run_points: list[EvalPoint]) -> bool:
    if not run_points:
        return False
    latest = run_points[-1]
    best = max(p.reward for p in run_points)
    if latest.step >= 600_000 and best < 8.0:
        return True
    if latest.step >= 1_200_000 and best < 18.0:
        return True
    if latest.step >= 2_000_000 and best < 28.0:
        return True
    if latest.step >= 3_000_000 and best < 42.0:
        return True
    if latest.step >= 4_000_000 and best < 55.0:
        return True
    if latest.step >= 5_000_000 and best < 65.0:
        return True
    if len(run_points) >= 5 and latest.step >= 1_200_000:
        recent_best = max(p.reward for p in run_points[-4:])
        return recent_best < best - 8.0
    return False


def should_stop_refinement(run_points: list[EvalPoint], global_best: EvalPoint | None) -> bool:
    if not run_points or global_best is None:
        return False
    latest = run_points[-1]
    global_score = precision_aware_score(global_best)
    local_best = max(precision_aware_score(point) for point in run_points)
    latest_score = precision_aware_score(latest)
    global_reward = global_best.reward
    local_reward_best = max(point.reward for point in run_points)
    reward_is_climbing = local_reward_best >= global_reward - 0.2 or latest.reward >= local_reward_best - 0.6
    if len(run_points) >= 2 and latest.step >= global_best.step + 800_000 and local_best < global_score - 1.2 and not reward_is_climbing:
        return True
    if len(run_points) >= 4 and local_best < global_score - 2.0 and local_reward_best < global_reward - 1.5:
        return True
    if len(run_points) >= 5 and local_best < global_score - 0.6 and local_reward_best < global_reward - 0.8:
        return True
    if len(run_points) >= 7 and latest_score < global_score - 0.8 and latest.reward < global_reward - 1.0:
        return True
    if len(run_points) >= 5 and latest_score < local_best - 1.0:
        return True
    return False


def refinement_generations_in_use(
    root: Path,
    best: EvalPoint,
    *,
    running: set[str],
    points: list[EvalPoint],
) -> set[int]:
    running_used: set[int] = set()
    seen_used: set[int] = set()
    best_prefix = f"rfpo_scratch_best{int(best.reward)}_"
    source_token = f"_{refinement_source_token(best)}_"
    seen_runs = {point.run_name for point in points}
    for idx, cfg in enumerate(REFINEMENT_GRID[:RFPO_REFINEMENT_GENERATIONS]):
        tag_token = f"_{cfg['tag']}_"
        for run in running:
            if run.startswith(best_prefix) and tag_token in run:
                running_used.add(idx)
                break
        if idx in running_used:
            continue
        for run in seen_runs:
            if run.startswith(best_prefix) and tag_token in run and source_token in run:
                seen_used.add(idx)
                break
    return running_used | seen_used


