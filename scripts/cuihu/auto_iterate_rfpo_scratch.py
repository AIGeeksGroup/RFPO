def tick(root: Path, repo: Path) -> None:
    points = all_points(root)
    write_record(root / "RFPO_from_scratch_当前最佳实验记录.md", root=root, points=points)
    current_best = best_point(points)
    processes = python_processes()
    stopped_any = False
    for run, (pid, _) in list(processes.items()):
        run_points = points_for(points, run)
        if should_stop_refinement(run_points, current_best) or should_stop_run(run_points):
            stop_run(pid)
            stopped_any = True
    if stopped_any:
        sync_desktop(root)
        return
    processes = python_processes()
    running = set(processes)
    occupied_gpus = busy_gpus()
    if current_best is not None and current_best.reward >= 70.0:
        active_refinements = sum(1 for run in running if is_refinement_run(run))
        used_generations = refinement_generations_in_use(
            root,
            current_best,
            running=running,
            points=points,
        )
        generation = 0
        for gpu in ACTIVE_GPUS:
            if active_refinements >= MAX_ACTIVE_REFINEMENTS:
                break
            if gpu in occupied_gpus:
                continue
            for attempt in range(RFPO_REFINEMENT_GENERATIONS):
                candidate_generation = (generation + attempt) % RFPO_REFINEMENT_GENERATIONS
                if candidate_generation in used_generations:
                    continue
                candidate = refinement_candidate(root, current_best, gpu=gpu, generation=candidate_generation)
                if candidate.run in running or points_for(points, candidate.run):
                    continue
                if refinement_source(candidate.overrides) == current_best.run_name:
                    used_generations.add(candidate_generation)
                launch(root, repo, candidate)
                running.add(candidate.run)
                occupied_gpus.add(gpu)
                active_refinements += 1
                break
            generation += 1
        sync_desktop(root)
        return
    for candidate in CANDIDATES:
        if candidate.run in running:
            continue
        if candidate.gpu in occupied_gpus:
            continue
        if points_for(points, candidate.run):
            continue
        launch(root, repo, candidate)
        processes = python_processes()
        occupied_gpus = busy_gpus() | {candidate.gpu}
    sync_desktop(root)


def locked_tick(root: Path, repo: Path) -> None:
    lock_path = root / "logs" / "auto_iterate_rfpo_scratch.lock"
    lock_path.parent.mkdir(parents=True, exist_ok=True)
    with lock_path.open("w") as lock_file:
        fcntl.flock(lock_file.fileno(), fcntl.LOCK_EX)
        tick(root, repo)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--root", default="/share/project/liyanjun/rongshanyu")
    parser.add_argument("--interval", type=int, default=300)
    parser.add_argument("--once", action="store_true")
    args = parser.parse_args()
    root = Path(args.root)
    repo = root / "vividex_sapien_server_upload_fpo_control_full"
    while True:
        locked_tick(root, repo)
        if args.once:
            break
        time.sleep(max(args.interval, 60))


