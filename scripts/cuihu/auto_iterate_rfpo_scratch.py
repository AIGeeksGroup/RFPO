def sh(cmd: str, *, cwd: Path | None = None) -> subprocess.CompletedProcess[str]:
    return subprocess.run(cmd, shell=True, cwd=cwd, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)


def python_processes() -> dict[str, tuple[int, str]]:
    proc = sh("ps -eo pid,args | grep 'python tools/train.py' | grep 'rfpo_scratch' | grep -v grep || true")
    found: dict[str, tuple[int, str]] = {}
    for line in proc.stdout.splitlines():
        match = re.match(r"\s*(\d+)\s+(.*)", line)
        if not match:
            continue
        pid = int(match.group(1))
        args = match.group(2)
        run_match = re.search(r"state_baseline/(rfpo_scratch[^/\s]+)", args)
        if run_match:
            found[run_match.group(1)] = (pid, args)
    return found


def process_cuda_visible_devices(pid: int) -> set[int]:
    env_path = Path("/proc") / str(pid) / "environ"
    try:
        env = env_path.read_bytes().split(b"\0")
    except OSError:
        return set()
    devices: set[int] = set()
    for item in env:
        if not item.startswith(b"CUDA_VISIBLE_DEVICES="):
            continue
        value = item.split(b"=", 1)[1].decode(errors="ignore")
        for part in value.split(","):
            part = part.strip()
            if part.isdigit():
                devices.add(int(part))
    return devices


def busy_gpus(min_free_mb: int | None = None) -> set[int]:
    if min_free_mb is None:
        min_free_mb = int(os.environ.get("RFPO_MIN_FREE_GPU_MB", "45000"))
    proc = sh("nvidia-smi --query-gpu=index,memory.used,memory.total --format=csv,noheader,nounits 2>/dev/null || true")
    low_free_gpus: set[int] = set()
    for line in proc.stdout.splitlines():
        parts = [part.strip() for part in line.split(",")]
        if len(parts) != 3:
            continue
        try:
            index = int(parts[0])
            used_mb = int(parts[1])
            total_mb = int(parts[2])
        except ValueError:
            continue
        if total_mb - used_mb < min_free_mb:
            low_free_gpus.add(index)
    busy: set[int] = set(low_free_gpus)
    for pid, _ in python_processes().values():
        busy.update(process_cuda_visible_devices(pid))
    return busy


