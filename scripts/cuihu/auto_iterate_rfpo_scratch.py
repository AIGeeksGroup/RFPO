def parse_gpu_list(value: str | None, default: tuple[int, ...]) -> tuple[int, ...]:
    if not value:
        return default
    gpus: list[int] = []
    for part in value.split(","):
        part = part.strip()
        if part.isdigit():
            gpus.append(int(part))
    return tuple(gpus) or default


